/** Runs against an isolated in-process SQLite database. Never uses app/data. */
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const dir = mkdtempSync(join(tmpdir(), 'banxue-regression-'));
process.env.BANXUE_DATA_DIR = dir;
const { q, db } = await import('../server/db.mjs');
const D = await import('../server/daily.mjs');
const V = await import('../server/v2.mjs');
let passed = 0;
function check(name, fn) { fn(); passed++; console.log(`✓ ${name}`); }
try {
 const child='continuation-test';
 q.run('INSERT INTO child(id,name,created_at) VALUES(?,?,?)',child,'验收',new Date().toISOString());
 D.adopt(child,{breed:'capybara_toon',name:'豆包'});
 const day=D.toDateKey();
 let rule=V.saveRule(child,{title:'原计划',weekdays:[1,2,3,4,5,6,7],basePoints:11})[0];
 let task=V.getStudentState(child).tasks[0];
 V.saveRule(child,{...rule,title:'新计划',basePoints:19});
 check('编辑计划同步今日待办并保留任务 ID',()=>{const t=V.getStudentState(child).tasks[0];assert.equal(t.title,'新计划');assert.equal(t.basePoints,19);assert.equal(t.id,task.id);});
 V.submitTask(child,task.id,{note:'第一次提交'});
 V.saveRule(child,{...rule,title:'下一版',basePoints:25});
 check('已提交任务保留提交时规则',()=>assert.equal(V.getStudentState(child).tasks[0].basePoints,19));
 V.reviewTask(child,task.id,{approve:false,reason:'请补充'});
 V.submitTask(child,task.id,{note:'已补充'});
 V.reviewTask(child,task.id,{approve:true});
 const balance=V.getStudentState(child).wallet.balance;
 check('退回后重提通过，只发一次积分',()=>{assert.equal(balance,19);assert.throws(()=>V.reviewTask(child,task.id,{approve:true}));assert.equal(V.getStudentState(child).wallet.balance,balance);});
 V.deleteRule(child,rule.id);
 check('删除规则保留已通过历史',()=>assert.equal(V.getStudentState(child).tasks[0].status,'approved'));
 rule=V.saveRule(child,{title:'待取消',weekdays:[1,2,3,4,5,6,7]})[0];
 V.deleteRule(child,rule.id);
 check('删除规则移除今日未提交任务',()=>assert.equal(V.getStudentState(child).tasks.length,1));
 check('非法时间和空星期被拒绝',()=>{assert.throws(()=>V.saveRule(child,{title:'坏时间',startTime:'29:90'}));assert.throws(()=>V.saveRule(child,{title:'空星期',weekdays:[]}));});
 V.giftPoints(child,{amount:100});
 const reward=V.saveReward(child,{title:'一起去公园',cost:20,stock:1})[0];
 V.redeemReward(child,reward.id);
 check('库存耗尽不能超兑',()=>assert.throws(()=>V.redeemReward(child,reward.id)));
 const redemption=V.listRedemptions(child)[0];const paid=V.getStudentState(child).wallet.balance;
 V.handleRedemption(child,redemption.id,'rejected');
 V.handleRedemption(child,redemption.id,'rejected');
 check('退回兑换只退款一次并恢复库存',()=>{assert.equal(V.getStudentState(child).wallet.balance,paid+20);assert.equal(V.listRewards(child)[0].stock,1);});
 check('无效兑现状态不写入',()=>assert.throws(()=>V.handleRedemption(child,redemption.id,'arbitrary')));
 D.interact(child,{action:'pet'}); D.interact(child,{action:'hug'});
 check('交替照顾不能绕过各动作冷却',()=>{assert.throws(()=>D.interact(child,{action:'pet'}));const c=V.getStudentState(child).cooldowns;assert(c.pet>0 && c.hug>0);});
 V.restPet(child); D.interact(child,{action:'play'});
 check('其他动作不能绕过小憩冷却',()=>assert.throws(()=>V.restPet(child)));
 V.giftPoints(child,{amount:500});
 D.buy(child,{key:'bow'});D.useMaterial(child,{key:'bow'});
 check('装扮按键名写入并可被舞台读取',()=>assert.equal(V.getStudentState(child).pet.outfit.bow,'1'));
 D.buy(child,{key:'crown'});D.useMaterial(child,{key:'crown'});
 check('不同部位装扮可同时穿戴',()=>{const outfit=V.getStudentState(child).pet.outfit;assert.equal(outfit.crown,'1');assert.equal(outfit.bow,'1');});
 V.saveRule(child,{title:'照片任务',weekdays:[1,2,3,4,5,6,7],photoRequired:true});
 const photoTask=V.getStudentState(child).tasks.find(t=>t.status==='open');
 check('照片任务拒绝漏传或无效图片，仍可重试',()=>{assert.throws(()=>V.submitTask(child,photoTask.id,{}));assert.throws(()=>V.submitTask(child,photoTask.id,{photo:'https://example.com/photo.jpg'}));assert.equal(V.getStudentState(child).tasks.find(t=>t.id===photoTask.id).status,'open');});
 V.submitTask(child,photoTask.id,{photo:'data:image/png;base64,iVBORw0KGgo='});
 const submittedPhoto=V.getStudentState(child).tasks.find(t=>t.id===photoTask.id);
 V.reviewTask(child,photoTask.id,{approve:false,reason:'请确认照片'});
 check('退回后可用原照片地址重提且状态不含内嵌图片',()=>{const t=V.submitTask(child,photoTask.id,{photo:submittedPhoto.photoUrl});assert.equal(t.photo,null);assert.equal(t.photoUrl,submittedPhoto.photoUrl);});
 const pendingBalance=V.getStudentState(child).wallet.balance;
 V.approveAll(child);V.approveAll(child);
 check('批量审核可重试，照片记录和积分保留',()=>{const t=V.getStudentState(child).tasks.find(t=>t.id===photoTask.id);assert.equal(t.status,'approved');assert(t.photoUrl);assert.equal(V.getStudentState(child).wallet.balance,pendingBalance+10);});
 // Fault injection verifies the ledger and status roll back together.
 V.saveRule(child,{title:'原子审核',weekdays:[1,2,3,4,5,6,7]});
 task=V.getStudentState(child).tasks.find(t=>t.status==='open');V.submitTask(child,task.id,{});
 db.exec(`CREATE TRIGGER fail_approval BEFORE UPDATE ON v2_task WHEN NEW.status='approved' BEGIN SELECT RAISE(ABORT, 'injected'); END`);
 const before=V.getStudentState(child).wallet.balance;
 check('审核中断回滚积分与状态',()=>{assert.throws(()=>V.reviewTask(child,task.id,{approve:true}));assert.equal(V.getStudentState(child).wallet.balance,before);assert.equal(V.getStudentState(child).tasks.find(t=>t.id===task.id).status,'submitted');});
 db.exec('DROP TRIGGER fail_approval');
 console.log(`${passed} regressions passed; isolated data: ${dir}`);
} finally { db.close(); rmSync(dir,{recursive:true,force:true}); }
