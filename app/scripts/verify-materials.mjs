/** Purchase, cleaning, permanent outfits and old-data compatibility in a disposable DB. */
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = mkdtempSync(join(tmpdir(), 'banxue-materials-'));
process.env.BANXUE_DATA_DIR = dir;
const { q, db } = await import('../server/db.mjs');
const D = await import('../server/daily.mjs');
const V = await import('../server/v2.mjs');
let checks = 0;
const check = (label, fn) => { fn(); checks++; console.log('✓ ' + label); };
const state = id => V.getStudentState(id);
const qty = (id, key) => state(id).inventory.find(x => x.key === key)?.qty || 0;
const create = id => q.run('INSERT INTO child(id,name,created_at) VALUES(?,?,?)', id, '材料验收', new Date().toISOString());
try {
  const id = 'material-test'; create(id);
  D.adopt(id, { breed: 'capybara_toon', name: '卡卡' }); V.giftPoints(id, { amount: 2000 });
  let before = state(id).wallet.balance;
  D.buy(id, { key: 'brush', qty: 2 });
  check('购买按数量扣款并入包', () => { assert.equal(qty(id, 'brush'), 2); assert.equal(state(id).wallet.balance, before - 64); });
  for (const n of [0, -1, .5, 10, Infinity, 'invalid']) check(`拒绝非法兑换数量 ${n}`, () => assert.throws(() => D.buy(id, { key: 'brush', qty: n })));
  q.run('UPDATE pet_life SET clean=20,mood=40 WHERE child_id=?', id);
  let used = D.useMaterial(id, { key: 'brush' });
  check('梳子只扣一件并增加真实清洁状态', () => { assert.equal(qty(id, 'brush'), 1); assert.equal(used.pet.stats.clean, 38); assert.equal(used.used.key, 'brush'); });
  D.useMaterial(id, { key: 'brush' });
  check('耗尽后拒绝再次使用，库存不为负', () => { assert.throws(() => D.useMaterial(id, { key: 'brush' })); assert.equal(qty(id, 'brush'), 0); });
  D.buy(id, { key: 'bath' }); used = D.useMaterial(id, { key: 'bath' });
  check('沐浴用品恢复清洁并返回物品身份', () => { assert.equal(used.pet.stats.clean, 92); assert.equal(used.used.key, 'bath'); assert.equal(qty(id, 'bath'), 0); });
  D.buy(id, { key: 'bow' }); before = state(id).wallet.balance;
  check('永久装扮禁止重复购买和批量购买且不扣款', () => { assert.throws(() => D.buy(id, { key: 'bow' })); assert.throws(() => D.buy(id, { key: 'crown', qty: 2 })); assert.equal(state(id).wallet.balance, before); });
  q.run('UPDATE pet_life SET mood=20 WHERE child_id=?', id);
  used = D.useMaterial(id, { key: 'bow' });
  check('首次穿戴奖励心情且保留装扮', () => { assert.equal(used.pet.stats.mood, 32); assert.equal(qty(id, 'bow'), 1); assert.equal(used.pet.outfit.bow, '1'); });
  D.buy(id, { key: 'crown' }); used = D.useMaterial(id, { key: 'crown' });
  check('皇冠和蝴蝶结分部位同时穿戴', () => assert.deepEqual(used.pet.outfit, { bow: '1', crown: '1' }));
  const mood = used.pet.stats.mood;
  used = D.useMaterial(id, { key: 'bow' });
  check('重复穿戴幂等，不重复奖励心情', () => { assert.equal(used.changed, false); assert.equal(used.pet.stats.mood, mood); });
  used = D.useMaterial(id, { key: 'bow', equipped: false });
  check('取下只移除对应部位，永久物品留在背包', () => { assert.equal(used.pet.outfit.bow, undefined); assert.equal(used.pet.outfit.crown, '1'); assert.equal(qty(id, 'bow'), 1); });
  used = D.useMaterial(id, { key: 'bow' });
  check('重新戴上不消耗、不重领心情', () => { assert.equal(used.pet.stats.mood, mood); assert.equal(qty(id, 'bow'), 1); });
  check('没有的物品不能使用或取下', () => { assert.throws(() => D.useMaterial(id, { key: 'invalid' })); assert.throws(() => D.useMaterial(id, { key: 'brush', equipped: false })); });
  const old = 'legacy-material'; create(old); D.adopt(old, { breed: 'dog_corgi_toon', name: '豆包' });
  q.run('UPDATE pet_life SET outfit=? WHERE child_id=?', JSON.stringify({ neck: 'bow' }), old);
  q.run('INSERT INTO point_ledger VALUES(?,?,?,?,?,?,?)', 'old-crown', old, D.toDateKey(), -260, '兑换材料：迷你小皇冠 ×1', 'legacy-crown', new Date().toISOString());
  check('旧版已消耗装扮从穿戴和购买记录找回', () => { assert.equal(qty(old, 'bow'), 1); assert.equal(qty(old, 'crown'), 1); });
  used = D.useMaterial(old, { key: 'crown' });
  check('旧版穿戴键格式兼容，不覆盖已有颈部装扮', () => { assert.deepEqual(used.pet.outfit, { bow: '1', crown: '1' }); assert.equal(used.pet.stats.mood, 86); });
  const empty = 'no-pet-material'; create(empty); V.giftPoints(empty, { amount: 200 }); D.buy(empty, { key: 'brush' });
  check('未领养不能消耗材料', () => { assert.throws(() => D.useMaterial(empty, { key: 'brush' })); assert.equal(qty(empty, 'brush'), 1); });
  check('跨孩子不能使用对方装扮', () => assert.throws(() => D.useMaterial(empty, { key: 'bow' })));
  const poor = 'poor-material'; create(poor);
  check('余额不足不入包、不扣款', () => { assert.throws(() => D.buy(poor, { key: 'crown' })); assert.equal(qty(poor, 'crown'), 0); assert.equal(state(poor).wallet.balance, 0); });
  q.run('INSERT INTO material_inv VALUES(?,?,?)', old, 'bow', 2);
  q.run('UPDATE material_wardrobe SET first_worn_at=NULL WHERE child_id=? AND item_key=?', old, 'bow');
  used = D.useMaterial(old, { key: 'bow' });
  check('旧版重复库存与已穿戴并存时不补发首次奖励', () => { assert.equal(used.pet.stats.mood, 86); assert.equal(qty(old, 'bow'), 1); });
  const rollback = 'material-rollback'; create(rollback); D.adopt(rollback, { breed: 'dog_corgi_toon', name: '验收' }); V.giftPoints(rollback, { amount: 1000 });
  const rollbackBalance = state(rollback).wallet.balance;
  db.exec("CREATE TRIGGER fail_material_purchase BEFORE INSERT ON material_inv WHEN NEW.child_id='material-rollback' BEGIN SELECT RAISE(ABORT,'injected purchase'); END");
  check('购买入包失败时整笔回滚扣款和永久所有权', () => { assert.throws(() => D.buy(rollback, { key: 'crown' }), /injected/); assert.equal(state(rollback).wallet.balance, rollbackBalance); assert.equal(qty(rollback, 'crown'), 0); });
  db.exec('DROP TRIGGER fail_material_purchase');
  D.buy(rollback, { key: 'crown' });
  db.exec("CREATE TRIGGER fail_material_wear BEFORE UPDATE ON pet_life WHEN NEW.child_id='material-rollback' BEGIN SELECT RAISE(ABORT,'injected outfit'); END");
  check('穿戴失败时首次奖励标记与宠物修改一并回滚', () => { assert.throws(() => D.useMaterial(rollback, { key: 'crown' }), /injected/); assert.equal(q.get('SELECT first_worn_at FROM material_wardrobe WHERE child_id=? AND item_key=?', rollback, 'crown').first_worn_at, null); assert.equal(q.get('SELECT outfit FROM pet_life WHERE child_id=?', rollback).outfit, '{}'); });
  db.exec('DROP TRIGGER fail_material_wear');
  const chest = 'material-chest'; create(chest); D.adopt(chest, { breed: 'capybara_toon', name: '验收' }); V.giftPoints(chest, { amount: 500 });
  D.buy(chest, { key: 'bow' }); D.buy(chest, { key: 'brush' });
  q.run('UPDATE pet_life SET stage=4,confirmed_level=7,growth=49 WHERE child_id=?', chest);
  const random = Math.random;
  try {
    Math.random = () => .9999;
    used = D.useMaterial(chest, { key: 'brush' });
    check('百宝箱排除已拥有的永久装扮，仍掉落实用材料', () => { assert.equal(used.loot.length, 1); assert.notEqual(used.loot[0].key, 'bow'); });
  } finally { Math.random = random; }
  console.log(`${checks} material checks passed`);
} finally { db.close(); rmSync(dir, { recursive: true, force: true }); }
