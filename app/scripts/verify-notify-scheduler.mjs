/** Persistent daily summary scheduling with fake delivery and a disposable database. */
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawn} from 'node:child_process';
const dir=mkdtempSync(join(tmpdir(),'banxue-summary-'));process.env.BANXUE_DATA_DIR=dir;
const {q,db}=await import('../server/db.mjs');await import('../server/accounts.mjs');
const V=await import('../server/v2.mjs'),N=await import('../server/notifications.mjs');
const {chinaClock,runDueSummaries}=await import('../server/notification-scheduler.mjs');
let checks=0;const ok=(condition,label)=>{assert.ok(condition,label);checks++;console.log('✓ '+label);};
const originalFetch=globalThis.fetch;globalThis.fetch=async()=>{throw Error('隔离测试禁止真实推送');};
const child='summary-kid',calls=[];
const fake=async(url,init)=>{calls.push({url,body:JSON.parse(init.body)});return {ok:true,status:200,json:async()=>url.includes('pushplus')?{code:200}:{errcode:0}};};
const future=Date.now()+86400000,day=chinaClock(future).date;
const at=(date,time)=>Date.parse(`${date}T${time}:00+08:00`);
const next=offset=>chinaClock(future+offset*86400000).date;
const concurrent=offset=>new Promise((resolve,reject)=>{
 const childProcess=spawn(process.execPath,['--import','./scripts/fixtures/notify-fetch.mjs','--input-type=module','-e',`import './server/accounts.mjs';import {runDueSummaries} from './server/notification-scheduler.mjs';await runDueSummaries({at:${at(next(offset),'21:00')}});`],{env:{...process.env,BANXUE_DATA_DIR:dir,BANXUE_NOTIFY_CAPTURE_PATH:join(dir,'deliveries.jsonl')},stdio:['ignore','ignore','pipe']});
 let error='';childProcess.stderr.on('data',d=>{error+=d;});childProcess.on('exit',code=>code===0?resolve():reject(Error(error)));childProcess.on('error',reject);
});
try{
 q.run('INSERT INTO child(id,name,created_at) VALUES(?,?,?)',child,'汇总孩子',new Date().toISOString());
 for(let i=0;i<5;i++)V.saveRule(child,{title:`汇总任务${i}`,subject:'自习',basePoints:10,weekdays:[1,2,3,4,5,6,7]});
 N.saveNotificationChannels(child,[{provider:'wecom',enabled:true,target:'https://qyapi.weixin.qq.com/cgi-bin/webhook/send?key=dummy_wecom'},{provider:'dingtalk',enabled:true,target:'https://oapi.dingtalk.com/robot/send?access_token=dummy_dingtalk',secret:'SECdummySigningSecret20261114'},{provider:'pushplus',enabled:true,target:'dummy_pushplus'}]);
 await runDueSummaries({at:at(day,'21:00'),fetchImpl:fake});
 ok(calls.length===0&&!q.get('SELECT * FROM notify_summary_run WHERE child_id=?',child),'每日汇总默认关闭，不发送也不占用当天记录');
 N.saveNotificationPreferences(child,{events:{daily_summary:true}});
 V.ensureTasks(child,day);
 const tasks=q.all('SELECT * FROM v2_task WHERE child_id=? AND date=? ORDER BY title',child,day);
 q.run("UPDATE v2_task SET status='approved',awarded_points=17 WHERE id=?",tasks[0].id);
 q.run("UPDATE v2_task SET status='approved',awarded_points=0 WHERE id=?",tasks[1].id);
 q.run("UPDATE v2_task SET status='submitted',awarded_points=99 WHERE id=?",tasks[2].id);
 q.run("UPDATE v2_task SET status='rejected' WHERE id=?",tasks[3].id);
 await runDueSummaries({at:at(day,'20:29'),fetchImpl:fake});ok(!calls.length,'北京时间到点前不发送');
 await runDueSummaries({at:at(day,'20:30'),fetchImpl:fake});
 const content=calls[0].body.text.content;
 ok(calls.length===3&&content.includes('今日计划 5 项')&&content.includes('完成率 40%')&&content.includes('已通过 2 · 待审核 1 · 未完成 1 · 已退回 1')&&content.includes('今日已赚 17 ★'),'到点向三个通道汇总准确状态，仅累计最终通过的实际星贝');
 ok(tasks.every(t=>content.includes(t.title))&&calls.every(c=>c.body.msgtype!=='actionCard'),'汇总包含全部任务状态明细，不误用待审核卡片');
 await runDueSummaries({at:at(day,'21:00'),fetchImpl:fake});
 N.saveNotificationPreferences(child,{time:'20:00'});await runDueSummaries({at:at(day,'21:00'),fetchImpl:fake});
 ok(calls.length===3,'重复轮询和当日改时间均不重复发送');
 N.saveNotificationPreferences(child,{time:'22:10'});
 await runDueSummaries({at:at(next(1),'22:09'),fetchImpl:fake});ok(calls.length===3,'修改推送时间后按新时间执行');
 await runDueSummaries({at:at(next(1),'23:00'),fetchImpl:fake});
 ok(calls.length===6&&calls.at(-1).body.content.includes(next(1)),'错过当日时间后补发一次；次日有独立发送记录');
 N.saveNotificationPreferences(child,{events:{daily_summary:false}});
 await runDueSummaries({at:at(next(2),'23:00'),fetchImpl:fake});ok(calls.length===6,'关闭汇总后不发送');
 N.saveNotificationPreferences(child,{events:{daily_summary:true},time:'20:30'});
 N.saveNotificationChannels(child,N.PROVIDERS.map(provider=>({provider,enabled:false})));
 await runDueSummaries({at:at(next(2),'23:00'),fetchImpl:fake});
 ok(!q.get('SELECT * FROM notify_summary_run WHERE child_id=? AND date=?',child,next(2)),'全部通道关闭时不占用当天发送机会');
 N.saveNotificationChannels(child,[{provider:'wecom',enabled:true}]);
 await runDueSummaries({at:at(next(2),'23:01'),fetchImpl:fake});ok(calls.length===7,'当天打开通道后补发，仍尊重通道开关');
 N.saveNotificationChannels(child,N.PROVIDERS.map(provider=>({provider,enabled:true})));
 await Promise.all([concurrent(3),concurrent(3)]);
 const captured=readFileSync(join(dir,'deliveries.jsonl'),'utf8').trim().split('\n');
 ok(captured.length===3&&q.get('SELECT count(*) n FROM notify_summary_run WHERE child_id=? AND date=?',child,next(3)).n===1,'两个独立服务并发调度时，仅一方发送，每通道一次');
 await concurrent(3);ok(readFileSync(join(dir,'deliveries.jsonl'),'utf8').trim().split('\n').length===3,'服务重启后不重复发送已推送的当天汇总');
 await runDueSummaries({at:at(next(4),'21:00'),fetchImpl:async()=>{throw Error('模拟超时');}});
 const failed=q.get('SELECT status FROM notify_summary_run WHERE child_id=? AND date=?',child,next(4));
 await runDueSummaries({at:at(next(4),'22:00'),fetchImpl:fake});
 ok(failed.status==='failed'&&calls.length===7&&N.notificationLogs(child,{status:'failed'}).items.length===3,'发送失败分别记录日志，不自动重复外发');
 q.run('INSERT INTO child(id,name,created_at) VALUES(?,?,?)','empty-kid','空计划孩子',new Date().toISOString());
 N.saveNotificationChannels('empty-kid',[{provider:'wecom',enabled:true,target:'https://qyapi.weixin.qq.com/cgi-bin/webhook/send?key=dummy_empty'}]);
 N.saveNotificationPreferences('empty-kid',{events:{daily_summary:true},time:'00:00'});
 await runDueSummaries({at:at(next(4),'23:00'),fetchImpl:fake});
 ok(calls.length===8&&calls.at(-1).body.text.content.includes('今天没有安排任务。'),'空计划孩子也有清晰的零任务汇总，孩子配置互不影响');
 assert.deepEqual(chinaClock(Date.parse('2026-11-15T16:00:00Z')),{date:'2026-11-16',time:'00:00'});
 assert.deepEqual(chinaClock(Date.parse('2026-11-15T15:59:00Z')),{date:'2026-11-15',time:'23:59'});
 ok(true,'北京时间零点及日期边界不依赖服务器时区');
 console.log(`${checks} daily summary checks passed`);
}finally{globalThis.fetch=originalFetch;db.close();rmSync(dir,{recursive:true,force:true});}
